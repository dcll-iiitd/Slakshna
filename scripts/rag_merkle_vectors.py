"""Write tests/fixtures/merkle_vectors.json, the shared Merkle test vectors.

    .venv-rag/bin/python scripts/rag_merkle_vectors.py

The file lists small inputs and every hash and proof rag/merkle.py computes
for them. The Python tests (tests/test_rag_merkle.py) and the Rust tests
(src/rag/merkle.rs) both check their code against it, which is how the two
languages are shown to hash exactly the same bytes.

Re-run this only on purpose: a changed fixture means the format changed, and
every node in a federation must then be upgraded together.
"""

import json
import os
import sys

import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, ROOT)

from rag.merkle import (  # noqa: E402
    Commitment, build_levels, centroid_bytes, cluster_hash, inner_hash, leaf_hash,
    levels_root, make_proof, signed_root_message,
)

FIXTURE_PATH = os.path.join(ROOT, "tests", "fixtures", "merkle_vectors.json")

# Plain ASCII, a 3-byte UTF-8 character (the em dash), a 4-byte one (the
# emoji), accented letters, and an empty text.
CHUNKS = [
    ("chandrayaan_3.pdf#0", "Chandrayaan-3 landed near the lunar south pole on 23 August 2023."),
    ("aditya_l1.pdf#2", "Aditya-L1 studies the Sun from the L1 point — 1.5 million km away."),
    ("gaganyaan.pdf#1", "Gaganyaan is India's crewed orbital spacecraft."),
    ("kaziranga.pdf#0", "Kāziranga hosts two-thirds of the world's great one-horned rhinos 🦏."),
    ("raman.pdf#5", "C. V. Raman won the Nobel Prize in Physics in 1930."),
    ("empty.txt#0", ""),
]

# 4-dimensional centroids. The hex form is what is hashed and sent; the
# float values are only for reading. 0.6 and -0.8 are not exact in float32,
# so the hex is the ground truth.
CENTROIDS = [
    [0.5, 0.5, 0.5, 0.5],
    [0.6, -0.8, 0.0, 0.0],
    [0.125, -0.25, 1.0, -2.0],
]


def tree_case(name, nodes):
    levels = build_levels(nodes)
    return {
        "name": name,
        "leaves": [node.hex() for node in nodes],
        "root": levels_root(levels).hex(),
        "proofs": [make_proof(levels, i) for i in range(len(nodes))],
    }


def commitment_case(name, chunks, assignments, centroids, dim):
    records = [{"chunk_id": cid, "text": text, "cluster": c}
               for (cid, text), c in zip(chunks, assignments)]
    centroids = np.asarray(centroids, dtype=np.float32).reshape(-1, dim)
    commitment = Commitment(records, centroids)
    clusters = []
    for c in range(commitment.num_clusters):
        entry = commitment.cluster_entry(c)
        entry["hash"] = cluster_hash(c, centroids[c], commitment.subtree_roots[c]).hex()
        clusters.append(entry)
    return {
        "name": name,
        "dim": dim,
        "chunks": [
            {**record, "leaf": leaf_hash(record["chunk_id"], record["text"]).hex(),
             "chunk_proof": commitment.chunk_proof(i)}
            for i, record in enumerate(records)
        ],
        "centroids": [{"values": [float(v) for v in row], "hex": centroid_bytes(row).hex()}
                      for row in centroids],
        "clusters": clusters,
        "root": commitment.root_hex,
    }


def build_vectors():
    leaves = [leaf_hash(cid, text) for cid, text in CHUNKS]
    three = commitment_case("three_clusters", CHUNKS, [0, 1, 0, 2, 0, 2], CENTROIDS, 4)
    signed = {
        "root": three["root"],
        "version": 1760774400123,
        "num_chunks": len(CHUNKS),
        "num_clusters": len(CENTROIDS),
        "dim": 4,
        "embedding_model": "sentence-transformers/all-MiniLM-L6-v2",
    }
    signed["message"] = signed_root_message(
        bytes.fromhex(signed["root"]), signed["version"], signed["num_chunks"],
        signed["num_clusters"], signed["dim"], signed["embedding_model"],
    ).hex()
    return {
        "about": "Shared Merkle test vectors; format defined in rag/merkle.py and src/rag/merkle.rs. "
                 "Generated by scripts/rag_merkle_vectors.py. Hashes are lowercase hex SHA-256.",
        "leaves": [{"chunk_id": cid, "text": text, "hash": h.hex()}
                   for (cid, text), h in zip(CHUNKS, leaves)],
        "inner": {"left": leaves[0].hex(), "right": leaves[1].hex(),
                  "hash": inner_hash(leaves[0], leaves[1]).hex()},
        "trees": [
            tree_case("empty", []),
            tree_case("one_leaf", leaves[:1]),
            tree_case("two_leaves", leaves[:2]),
            tree_case("three_leaves", leaves[:3]),
            tree_case("five_leaves", leaves[:5]),
        ],
        "commitments": [
            three,
            commitment_case("one_cluster", CHUNKS[:3], [0, 0, 0], CENTROIDS[:1], 4),
            commitment_case("empty", [], [], [], 4),
        ],
        "signed_root": signed,
    }


def main():
    os.makedirs(os.path.dirname(FIXTURE_PATH), exist_ok=True)
    with open(FIXTURE_PATH, "w", encoding="utf-8") as f:
        json.dump(build_vectors(), f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"Wrote {FIXTURE_PATH}", file=sys.stderr)


if __name__ == "__main__":
    main()
